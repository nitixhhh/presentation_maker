export function getRandomPalette(seed?: number): ColorPalette {
  const index = seed !== undefined ? Math.abs(seed) % CURATED_PALETTES.length : Math.floor(Math.random() * CURATED_PALETTES.length);
  return CURATED_PALETTES[index];
}

export function getPaletteById(id: string): ColorPalette | undefined {
  return CURATED_PALETTES.find((p) => p.id === id);
}
